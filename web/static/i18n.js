let idiomaActual = localStorage.getItem(CLAVE_IDIOMA) || "";
let idiomaInfo = null;

function idiomaElegido() {
  return idiomaActual || IDIOMA_POR_DEFECTO;
}

/* Devuelve el texto de una clave en el idioma activo, con los marcadores {x}
   sustituidos. Si falta la clave, cae al español y, si tampoco está, devuelve
   la propia clave (así se ve enseguida qué falta por traducir). */
function t(clave, valores) {
  const dic = TEXTOS[idiomaElegido()] || {};
  let texto = dic[clave];
  if (texto === undefined) texto = (TEXTOS[IDIOMA_POR_DEFECTO] || {})[clave];
  if (texto === undefined) return clave;
  if (valores) {
    Object.keys(valores).forEach((k) => {
      texto = texto.split("{" + k + "}").join(valores[k]);
    });
  }
  return texto;
}

function localeDeIdioma() {
  const i = idiomaInfo || IDIOMAS.find((x) => x.code === idiomaElegido());
  return (i && i.locale) || "es-VE";
}

/* Elige el idioma inicial: lo guardado, lo que pide el navegador o el español. */
function detectarIdioma() {
  if (idiomaActual) return idiomaActual;
  const navegador = (navigator.language || navigator.userLanguage || "").toLowerCase();
  const base = navegador.split("-")[0];
  const conocido = IDIOMAS.find((i) => i.code === base);
  return conocido ? conocido.code : IDIOMA_POR_DEFECTO;
}
